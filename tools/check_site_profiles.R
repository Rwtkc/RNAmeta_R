library(data.table)
set.seed(1)
source("R/RNAmeta_gene_type_export.R")
source("R/RNAmeta_cache_core.R")
source("R/RNAmeta_chart_core.R")
source("R/RNAmeta_chart_export.R")
source("R/RNAmeta_site_profile_core.R")
source("R/RNAmeta_get_transcription_plot.R")
source("R/RNAmeta_get_translation_plot.R")
source("R/RNAmeta_get_splicesite_plot.R")
source("R/RNAmeta_meta_widget.R")
hits <- rbindlist(list(
 data.table(feature=rep(c("Transcription_start_site","Transcription_end_site"),each=200),Sample="Group1",rel_pos=c(rnorm(200,-50,180),rnorm(200,40,210)),xmin=-1000,xmax=999),
 data.table(feature=rep(c("Transcription_start_site","Transcription_end_site"),each=200),Sample="Group2",rel_pos=c(rnorm(200,20,150),rnorm(200,-20,190)),xmin=-1000,xmax=999)))
heat <- list(-99:100,-99:100,matrix(rexp(100*200),100,200),matrix(rexp(120*200),120,200))
data <- list(hits,stats::setNames(list(heat,heat),c("Group1","Group2")))
plots <- .rnameta_site_profile_plot(data,c("Up","Down"),"Transcription")
stopifnot(inherits(plots,"RNAmeta_site_profile_plots"),length(plots)==6,all(vapply(plots,inherits,logical(1),"htmlwidget")),all(vapply(plots,function(x) length(x$x$config$panels)==1L,logical(1))))
public_plots <- RNAmeta_get_transcription_plot(data,c("Up","Down"))
stopifnot(inherits(public_plots,"RNAmeta_site_profile_plots"),length(public_plots)==6)
public_single <- RNAmeta_get_transcription_plot(data,c("Up","Down"),panel="Transcription_end_site")
stopifnot(inherits(public_single,"htmlwidget"),identical(public_single$x$config$panels[[1]]$key,"Transcription_end_site"))
splice_hits <- copy(hits)[, feature := fifelse(feature == "Transcription_start_site", "5PSS", "3PSS")]
splice_plots <- RNAmeta_get_splicesite_plot(splice_hits,c("Up","Down"))
stopifnot(inherits(splice_plots,"RNAmeta_site_profile_plots"),length(splice_plots)==2)
single <- .rnameta_site_profile_plot(data,c("Up","Down"),"Transcription",panel="Transcription_start_site")
stopifnot(inherits(single,"htmlwidget"),length(single$x$config$panels)==1L,identical(single$x$config$panels[[1]]$key,"Transcription_start_site"))
dir.create("tools/.tmp-site-output",showWarnings=FALSE)
on.exit(unlink("tools/.tmp-site-output", recursive = TRUE, force = TRUE), add = TRUE)
paths <- .rnameta_site_profile_export(data,"tools/.tmp-site-output/site.png",c("Up","Down"),"Transcription",width=1180,height=560,scale=1)
stopifnot(length(paths)==6,all(file.exists(paths)),all(file.info(paths)$size>1000),all(grepl("site_",basename(paths),fixed=TRUE)))
single_path <- .rnameta_site_profile_export(data,"tools/.tmp-site-output/site-start.pdf",c("Up","Down"),"Transcription",panel="Transcription_start_site")
stopifnot(length(single_path)==1,file.exists(single_path),file.info(single_path)$size>1000)
error <- try(.rnameta_site_profile_plot(data,c("Up","Down"),"Transcription",panel="missing"),silent=TRUE)
stopifnot(inherits(error,"try-error"))
meta_data <- rbindlist(list(data.table(x=seq(0,1,length.out=256),density=dnorm(seq(-3,3,length.out=256)),group="Up"),data.table(x=seq(0,1,length.out=256),density=dnorm(seq(-3,3,length.out=256),.5),group="Down")))
meta <- .rnameta_chart_widget(.rnameta_meta_payload(meta_data,c(promoter=.2,rna=.6,tail=.2),"Distribution on Transcript"))
mrna <- .rnameta_chart_widget(.rnameta_meta_payload(meta_data,c(promoter=.12,utr5=.13,cds=.48,utr3=.15,tail=.12),"Distribution on mRNA"))
RNAmeta_meta_plot_export(meta,"tools/.tmp-site-output/meta.pdf")
RNAmeta_meta_plot_export(mrna,"tools/.tmp-site-output/mrna.png",width=1180,height=620,scale=1)
stopifnot(file.info("tools/.tmp-site-output/meta.pdf")$size>1000,file.info("tools/.tmp-site-output/mrna.png")$size>1000,identical(vapply(meta$x$config$components$segments,`[[`,character(1),"label"),c("Promoter(1kb)","RNA","Tail(1kb)")),identical(vapply(mrna$x$config$components$segments,`[[`,character(1),"label"),c("Promoter(1kb)","5'UTR","CDS","3'UTR","Tail(1kb)")))
cat("site_separate_widgets: TRUE\nsite_multi_export: TRUE\nsite_single_selection: TRUE\nsite_invalid_selection: TRUE\nmeta_widget_export: TRUE\nmeta_component_structure: TRUE\n")